create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = timezone('utc', now());
    return new;
end;
$$;

drop trigger if exists users_touch_updated_at on public.users;
create trigger users_touch_updated_at
before update on public.users
for each row execute function public.touch_updated_at();

drop trigger if exists subscriptions_touch_updated_at on public.subscriptions;
create trigger subscriptions_touch_updated_at
before update on public.subscriptions
for each row execute function public.touch_updated_at();

drop trigger if exists ssh_profiles_metadata_touch_updated_at on public.ssh_profiles_metadata;
create trigger ssh_profiles_metadata_touch_updated_at
before update on public.ssh_profiles_metadata
for each row execute function public.touch_updated_at();

drop trigger if exists snippets_touch_updated_at on public.snippets;
create trigger snippets_touch_updated_at
before update on public.snippets
for each row execute function public.touch_updated_at();

drop trigger if exists server_monitors_touch_updated_at on public.server_monitors;
